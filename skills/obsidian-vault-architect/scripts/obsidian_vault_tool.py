        for folder, note_list in sorted(folders.items()):
            folder_title = "🌐 ルート直下" if folder == "Root" else f"📁 {folder}"
            moc_content += f"### {folder_title}\n"
            for n in sorted(note_list):
                tags_str = " ".join([f"#{t}" for t in notes[n]["tags"]])
