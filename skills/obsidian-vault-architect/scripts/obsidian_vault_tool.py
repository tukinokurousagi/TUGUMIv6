def main():
    parser = argparse.ArgumentParser(description="Obsidian Vault Manager by つぐみ")
    parser.add_argument("--vault", default=DEFAULT_VAULT_DIR, help="Path to Obsidian Vault")
    subparsers = parser.add_subparsers(dest="command")

    # audit コマンド
    subparsers.add_parser("audit", help="Audit vault health (orphans, broken links)")

    # moc コマンド
    moc_parser = subparsers.add_parser("moc", help="Generate or update MOC note")
    moc_parser.add_argument("--output", default="00_TUGUMI_Auto_MOC.md", help="Output MOC filename")

    # heal コマンド
    subparsers.add_parser("heal", help="Auto-heal broken links by generating structured stub notes")

    args = parser.parse_args()

    try:
        manager = ObsidianVaultManager(args.vault)
    except Exception as e:
        print(f"[ERROR] {e}", file=sys.stderr)
        sys.exit(1)

    if args.command == "audit" or not args.command:
        res = manager.audit_vault()
        print("=== 💎 Obsidian Vault Audit Report ===")
        print(f"Vault: {args.vault}")
        print(f"Total Notes: {res['total_notes']}")
        print(f"Total Unique Link Targets: {res['total_links']}")
        print(f"Folders: {', '.join(res['folders'])}")
        print(f"Orphan Notes: {len(res['orphan_notes'])} ({', '.join(res['orphan_notes']) if res['orphan_notes'] else 'None'})")
        print(f"Unreferenced Notes: {len(res['unreferenced_notes'])}")
        print(f"Broken Links: {len(res['broken_links'])}")
        if res['broken_links']:
            for src, targets in res['broken_links'].items():
                print(f"  - In [[{src}]]: missing -> {targets}")
    elif args.command == "moc":
        out = manager.generate_moc(args.output)
        print(f"[SUCCESS] Generated MOC at: {out}")
    elif args.command == "heal":
        created = manager.heal_broken_links()
        print(f"[SUCCESS] Healed {len(created)} broken links by creating structured notes:")
        for name, path in created.items():
            print(f"  - [[{name}]] -> {path}")
        print("\n=== Re-auditing Vault ===")
        re_audit = manager.audit_vault()
        print(f"Remaining Broken Links: {len(re_audit['broken_links'])}")
        print(f"Total Notes: {re_audit['total_notes']}")


if __name__ == "__main__":
    main()
